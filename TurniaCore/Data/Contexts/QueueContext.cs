using System.Security.Claims;
using System.Reflection;
using TurniaCore.Data.Constants;
using TurniaCore.Libraries.DateTimeLibrary;
using TurniaCore.Entities.Platform.User;
using Microsoft.AspNetCore.Http;
using Microsoft.EntityFrameworkCore;
using TurniaCore.Data.Entities.BaseEntities;
using Microsoft.AspNetCore.Identity.EntityFrameworkCore;
using TurniaCore.Data.Entities.Platform.Devices;
using TurniaCore.Data.Entities.Platform.User;
using TurniaCore.Data.Entities.App.Shared;
using TurniaCore.Data.Entities.App.Queue;

namespace TurniaCore.Data
{
    public class QueueContext : IdentityDbContext<QueueUserProfile, QueueUserRole, Guid>
    {
        private readonly IHttpContextAccessor _httpContextAccessor = null!;

        public QueueContext(DbContextOptions<QueueContext> options, IHttpContextAccessor httpContextAccessor) : base(options)
        {
            _httpContextAccessor = httpContextAccessor;
        }

        public QueueContext(DbContextOptions<QueueContext> options) : base(options)
        {
        }

        #region Queue
        public DbSet<Counter> Counters { get; set; }
        public DbSet<Service> Services { get; set; }
        public DbSet<Ticket> Tickets { get; set; }
        #endregion

        #region Devices
        public DbSet<DeviceConfigurationCheckin> DeviceConfigurationCheckin { get; set; }
        public DbSet<DeviceConfigurationViewerScreens> DeviceConfigurationViewerScreens { get; set; }

        #endregion

        #region Authentication
        public DbSet<JwtBlacklistedTokens> JwtBlacklistedTokens { get; set; }
        public DbSet<JwtRefreshTokens> JwtRefreshTokens { get; set; }

        #endregion

        protected override void OnConfiguring(DbContextOptionsBuilder optionsBuilder)
        {
            optionsBuilder.EnableDetailedErrors();
            optionsBuilder.EnableSensitiveDataLogging();

            AppContext.SetSwitch("Npgsql.EnableLegacyTimestampBehavior", true);
        }

        #region OnBeforeSaveChanges

        private void SaveChangesOverride()
        {
            try
            {
                var modifiedEntries = ChangeTracker.Entries().Where(x => x.State is EntityState.Added or EntityState.Modified);

                string username = ConstantDefinitions.GeneratedByUnknown; ;
                string identityName = ConstantDefinitions.GeneratedByUnknown; 

                if (_httpContextAccessor == null)
                {
                    username = ConstantDefinitions.GeneratedByUnknown;
                    identityName = ConstantDefinitions.GeneratedByUnknown;
                }
                else 
                {
                    if (_httpContextAccessor.HttpContext != null)
                    {
                        username = _httpContextAccessor.HttpContext.User.FindFirst(ClaimTypes.Name)?.Value!;
                    }
                    
                    if (!string.IsNullOrEmpty(username))
                    {
                        identityName = username;
                    }
                }

                var now = DateTimeLibrary.Now;

                foreach (var entry in modifiedEntries)
                {
                    var entity = entry.Entity as BaseEntity;

                    if (entry.State == EntityState.Added)
                    {
                        if (entity != null)
                        {
                            if (entity.CreatedBy == ConstantDefinitions.AutoGeneratedBySystem)
                            {
                                entity.CreatedById = ConstantDefinitions.AutoGeneratedBySystemId;
                            }
                            else
                            {
                                if (entity.CreatedBy != ConstantDefinitions.GeneratedByUnknown)
                                {
                                    entity!.CreatedBy = identityName ?? ConstantDefinitions.GeneratedByUnknown;

                                    entity.CreatedById = ConstantDefinitions.GeneratedByUnknownId;
                                }
                            }

                            entity.Created = now;

                            entity.CreatedById = ConstantDefinitions.GeneratedByUnknownId;

                            entity.CreatedBy = identityName ?? ConstantDefinitions.GeneratedByUnknown;
                            entity.Created = now;
                        }
                    }

                    if (entity == null) continue;
                    entity.ModifiedBy = identityName ?? ConstantDefinitions.GeneratedByUnknown;
                    entity.Modified = now;
                }
            }
            catch (Exception e)
            {
                Console.WriteLine(e);
                throw;
            }
        }

        #endregion


protected override void OnModelCreating(ModelBuilder builder)
        {
            base.OnModelCreating(builder);

            #region Apply Entities Configuration
            var types = builder.Model.GetEntityTypes().Select(t => t.ClrType).ToHashSet();

            builder.ApplyConfigurationsFromAssembly(
           Assembly.GetExecutingAssembly(),
           t => t.GetInterfaces()
               .Any(i => i.IsGenericType
                   && i.GetGenericTypeDefinition() == typeof(IEntityTypeConfiguration<>)
                   && types.Contains(i.GenericTypeArguments[0]))
       );
            #endregion
        }


#region Overrided Methods

        public override async Task<int> SaveChangesAsync(CancellationToken cancellationToken = default)
        {
            SaveChangesOverride();

            return (await base.SaveChangesAsync(true, cancellationToken));


        }

        public async Task<int> SaveChangesAsyncWithoutOverride(CancellationToken cancellationToken = default)
        {
            return (await base.SaveChangesAsync(true, cancellationToken));
        }

        #endregion


        public async Task ApplyPendingMigrationsAsync()
        {
            await base.Database.MigrateAsync();
        }
    }
}
